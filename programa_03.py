#CALCULADORA python

num1 = int(input("Digite o Primeiro número: "))

num2 = int(input("Digite o segundo número: "))

soma = num1 + num2
print(f"A soma de {num2} e {num1} é igual a = {soma}")

subtracao = num1 - num2
print(f"A subtração do {num2} e {num1} é igual a = {subtracao}")

multiplicacao = num1 * num2
print(f"A multiplicação do {num2} e {num1} é igual a = {multiplicacao}")

divisao = num1 / num2
print(f"A divisão do {num1} e o {num2} é igual a = {divisao}")

divisao_inteira = num1 // num2
print(f"A divisão inteira dos numeros {num2} e {num1} e igual = {divisao_inteira}")

resto_da_divisao = num1 % num2
print(f"O resto da divisão dos numeros {num1} e {num2} é igual a = {resto_da_divisao}")

potenciacao = num1 ** num2
print(f"A potencialização dos {num2} e o {num1} é igual a = {potenciacao}")
